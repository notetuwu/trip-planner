// Local model servers (Ollama, LM Studio, llama.cpp, Jan, vLLM…), detected by probing their default ports.
// More can be added with LOCAL_LLM_URLS (comma-separated base URLs).
import type { LocalModel } from "../../shared/types";
import { getJson } from "../util/http";

export const OLLAMA_URL = process.env.OLLAMA_URL || "http://127.0.0.1:11434";

/** OpenAI-compatible servers on their default ports: [display name, base URL]. */
export const OPENAI_COMPAT: [string, string][] = [
  ["LM Studio", "http://127.0.0.1:1234"], ["llama.cpp / LocalAI", "http://127.0.0.1:8080"],
  ["Jan", "http://127.0.0.1:1337"], ["vLLM", "http://127.0.0.1:8000"], ["KoboldCpp", "http://127.0.0.1:5001"],
  ["text-generation-webui", "http://127.0.0.1:5000"], ["GPT4All", "http://127.0.0.1:4891"],
  ...(process.env.LOCAL_LLM_URLS || "").split(",").map((u) => u.trim()).filter(Boolean)
    .map((u): [string, string] => [new URL(u).host, u.replace(/\/+$/, "")]),
];

/** A server's display name for prompts and the "generated by" line. */
export const serverName = (kind: string, base: string) =>
  kind === "ollama" ? "Ollama" : OPENAI_COMPAT.find(([, b]) => b === base)?.[0] || base;

/** Model ids look like "local|ollama|<base>|<model>" or "local|openai|<base>|<model>". */
export function parseModelId(id: string) {
  const [, kind, base, model] = id.split("|");
  return { kind: kind as "ollama" | "openai", base, model };
}

export async function detectLocalModels(): Promise<LocalModel[]> {
  const found: LocalModel[] = [];
  const probes = [
    getJson(`${OLLAMA_URL}/api/tags`).then((d) => {
      for (const m of d.models || []) found.push({ id: `local|ollama|${OLLAMA_URL}|${m.name}`, name: m.name, server: "Ollama", size: m.size });
    }),
    ...OPENAI_COMPAT.map(([server, base]) => getJson(`${base}/v1/models`).then((d) => {
      if (!Array.isArray(d?.data)) return;
      for (const m of d.data) if (m.id && !/embed/i.test(m.id)) found.push({ id: `local|openai|${base}|${m.id}`, name: m.id, server });
    })),
  ];
  await Promise.allSettled(probes);
  return found;
}
